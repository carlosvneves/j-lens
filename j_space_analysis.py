def analyze_prompt_with_lens(user_prompt, layer_stride=2):
    """
    Performs Jacobian Lens analysis on a prompt and generates a response.
    """
    # Determine layers based on lens support (0-30)
    layers = list(range(0, 31, layer_stride))

    # 1. Lens Analysis
    jlens_logits, model_logits, _ = lens.apply(model, user_prompt, layers=layers, positions=[-2])
    logit_lens, _, _ = lens.apply(model, user_prompt, layers=layers, positions=[-2], use_jacobian=False)

    print(f"--- Analysis for Prompt: '{user_prompt}' ---\n")
    for layer in layers:
        print(f"L{layer:>2} logit-lens: {top20(logit_lens[layer][0])}")
        print(f"L{layer:>2} J-lens:     {top20(jlens_logits[layer][0])}")
        if layer % 4 == 0: print("-" * 20)

    # 2. Generation
    inputs = tokenizer(user_prompt, return_tensors="pt").to("cuda")
    outputs = hf_model.generate(
        **inputs,
        max_new_tokens=512,
        do_sample=False,
        pad_token_id=tokenizer.eos_token_id
    )
    full_response = tokenizer.decode(outputs[0][inputs.input_ids.shape[1]:], skip_special_tokens=True)

    # 3. Process thinking block
    if "<think>" in full_response and "</think>" in full_response:
        parts = full_response.split("</think>")
        thought = parts[0].replace("<think>", "").strip()
        final_answer = parts[1].strip()
    else:
        thought = "N/A (No thinking block detected or incomplete)"
        final_answer = full_response.strip()

    print(f"\nTop Model Predictions for next token: {top20(model_logits[0])[:5]}")
    print(f"\n--- MODEL THINKING PROCESS ---\n{thought}")
    print(f"\n--- FINAL VERDICT ---\n{final_answer}")
    print("="*50 + "\n")


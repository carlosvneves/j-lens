def analyze_and_visualize(user_prompt, target_tokens=None, layer_stride=2):
    """
    Flexible analysis function that tracks target tokens and returns data for split rendering.
    Separating text/data from HTML visualization prevents Colab environment crashes.
    """
    if target_tokens is None:
        target_tokens = ["Yes", "no"]

    target_ids = {t: tokenizer.encode(t, add_special_tokens=False)[0] for t in target_tokens}
    layers = list(range(0, 31, layer_stride))

    # 1. Lens Analysis
    logit_lens, _, _ = lens.apply(model, user_prompt, layers=layers, positions=[-2], use_jacobian=False)

    confidence_data = []
    print(f"--- LAYER-BY-LAYER TOP PREDICTIONS ---")
    for l in layers:
        l_logits = logit_lens[l][0]
        row = {"Layer": l}
        for token_text, t_id in target_ids.items():
            row[f"{token_text} Logit"] = float(l_logits[t_id])

        top_indices = l_logits.topk(10).indices
        top_tokens = [tokenizer.decode([idx]) for idx in top_indices]
        row["Top Prediction"] = top_tokens[0]
        confidence_data.append(row)
        print(f"L{l:>2}: {top_tokens}")

    df_confidence = pd.DataFrame(confidence_data)

    # 2. Model Generation
    inputs = tokenizer(user_prompt, return_tensors="pt").to("cuda")
    outputs = hf_model.generate(
        **inputs,
        max_new_tokens=512,
        do_sample=False,
        pad_token_id=tokenizer.eos_token_id
    )
    response = tokenizer.decode(outputs[0][inputs.input_ids.shape[1]:], skip_special_tokens=True)

    if "<think>" in response and "</think>" in response:
        thought, verdict = response.split("</think>")
        thought = thought.replace("<think>", "").strip()
    else:
        thought, verdict = "N/A", response.strip()

    # 3. Prepare Visuals (without displaying yet)
    # slice_data = compute_slice(model, lens, user_prompt, layer_stride=layer_stride, mask_display=True)
    # page, _, _ = build_page(
    #     slice_data,
    #     user_prompt,
    #     title="Jacobian Lens Analysis",
    #     description=f"Analysis for: {user_prompt}",
    #     alt_token=gloss
    # )


    # Load the gloss for token translation
    gloss = {
        int(k): v for k, v in json.load(gzip.open("/content/jacobian-lens-581d398613e5602a5af361e1c34d3a92ea82ba8e/assets/qwen_gloss.json.gz")).items()
    }

    # Compute slice for the visualization
    slice_data = compute_slice(
        model,
        lens,
        user_prompt,
        layer_stride=2,
        mask_display=True,
    )

    # Build and display the interactive page
    page, _, _ = build_page(
        slice_data,
        user_prompt,
        title="Price-Fixing Legal Analysis",
        description=f"User prompt: {user_prompt}",
        alt_token=gloss,
    )


    return df_confidence, thought, verdict, page

